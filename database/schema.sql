-- Schema PostgreSQL para a aplicação Finanças Simples (Spring Boot + Frontend Vue.js)
-- Compatível com a entidade JPA br.com.unicuritiba.financas.models.Transaction

CREATE TABLE IF NOT EXISTS transactions (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type             VARCHAR(16)    NOT NULL CHECK (type IN ('income', 'expense')),
    amount           NUMERIC(12, 2) NOT NULL CHECK (amount > 0),
    description      VARCHAR(120)   NOT NULL CHECK (char_length(trim(description)) > 0),
    category         VARCHAR(60)    NOT NULL DEFAULT 'Outros',
    transaction_date DATE           NOT NULL,
    created_at       TIMESTAMPTZ    NOT NULL DEFAULT NOW(),
    updated_at       TIMESTAMPTZ    NOT NULL DEFAULT NOW()
);

-- Índices alinhados às consultas do TransactionRepository (ordenação e filtros)
CREATE INDEX IF NOT EXISTS idx_transactions_date_created_id
    ON transactions (transaction_date DESC, created_at DESC, id DESC);

CREATE INDEX IF NOT EXISTS idx_transactions_type
    ON transactions (type);

CREATE INDEX IF NOT EXISTS idx_transactions_category
    ON transactions (category);

-- Trigger para atualizar updated_at automaticamente em updates diretos no banco
CREATE OR REPLACE FUNCTION set_transactions_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_transactions_updated_at ON transactions;
CREATE TRIGGER trg_transactions_updated_at
    BEFORE UPDATE ON transactions
    FOR EACH ROW
    EXECUTE FUNCTION set_transactions_updated_at();
